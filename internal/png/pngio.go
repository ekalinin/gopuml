// RasterImage is an image to write: ARGB pixels (0xAARRGGBB,
// non-premultiplied) row by row, upstream's BufferedImage of type
// TYPE_INT_ARGB, or TYPE_INT_RGB when HasAlpha is false (the alpha of its
// pixels is then ignored).
type RasterImage struct {
	Width, Height int
	Pix           []uint32
	HasAlpha      bool
}

// copyleft is the tEXt chunk upstream adds to every PNG.
const copyleft = "Generated by https://plantuml.com"

// Write writes an image as upstream's PngIO.write does: an opaque image
// whose colors fall in 32 to 256 RGB555 cubes is reduced to a palette of
// their most frequent colors, other images get the lowest bit of each
// channel replaced by the highest one; then the PNG gets a tEXt chunk
// "copyleft", the iTXt chunk "plantuml" with metadata (compressed) unless
// metadata is empty, and a pHYs chunk when dpi is not 96.
//
// The pixels written are upstream's; the compressed image data may differ
// from Java's PNG writer, which filters and compresses differently.
func Write(w io.Writer, img RasterImage, metadata string, dpi int) error {
	if img.Width <= 0 || img.Height <= 0 || len(img.Pix) != img.Width*img.Height {
		return errors.New("png: bad image size")
	}
	var src image.Image
	packed := false
	if !img.HasAlpha {
		opaque := make([]uint32, len(img.Pix))
		for i, v := range img.Pix {
			opaque[i] = v | 0xFF000000
		}
		if palette, indices, ok := quantify555(opaque); ok {
			pal := make(color.Palette, len(palette))
			for i, c := range palette {
				pal[i] = color.NRGBA{R: uint8(c >> 16), G: uint8(c >> 8), B: uint8(c), A: uint8(c >> 24)}
			}
			src = &image.Paletted{Pix: indices, Stride: img.Width, Rect: image.Rect(0, 0, img.Width, img.Height),
				Palette: pal}
			packed = true
		}
	}
	if !packed {
		nrgba := image.NewNRGBA(image.Rect(0, 0, img.Width, img.Height))
		for i, v := range img.Pix {
			v = compressPackedARGB(v)
			if !img.HasAlpha {
				v |= 0xFF000000
			}
			nrgba.Pix[4*i] = uint8(v >> 16)
			nrgba.Pix[4*i+1] = uint8(v >> 8)
			nrgba.Pix[4*i+2] = uint8(v)
			nrgba.Pix[4*i+3] = uint8(v >> 24)
		}
		src = nrgba
	}
	return WriteWithMetadata(w, src, metadata, dpi)
}

// WriteWithMetadata encodes an image as PNG with upstream's metadata
// chunks (PngIOMetadata.writeWithMetadata): pHYs when dpi is not 96, tEXt
// "copyleft", and iTXt "plantuml" (compressed, empty language tag and
// translated keyword) unless metadata is empty.
func WriteWithMetadata(w io.Writer, img image.Image, metadata string, dpi int) error {
	var encoded bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.DefaultCompression}
	if err := enc.Encode(&encoded, img); err != nil {
		return err
	}
	var extra [][]byte
	if dpi != 96 {
		extra = append(extra, physChunk(dpi))
	}
	extra = append(extra, pngChunk("tEXt", append(append([]byte("copyleft"), 0), latin1Bytes(copyleft)...)))
	if metadata != "" {
		it, err := itxtChunk("plantuml", metadata)
		if err != nil {
			return err
		}
		extra = append(extra, it)
	}
	return insertChunks(w, encoded.Bytes(), extra)
}

// pngChunk returns a PNG chunk: length, type, data, CRC.
func pngChunk(kind string, data []byte) []byte {
	out := make([]byte, 8, 12+len(data))
	binary.BigEndian.PutUint32(out, uint32(len(data)))
	copy(out[4:], kind)
	out = append(out, data...)
	crc := crc32.NewIEEE()
	crc.Write(out[4:])
	return binary.BigEndian.AppendUint32(out, crc.Sum32())
}

// latin1Bytes encodes text in ISO-8859-1, '?' for other characters, as
// Java's PNG writer does for tEXt chunks.
func latin1Bytes(s string) []byte {
	out := make([]byte, 0, len(s))
	for _, r := range s {
		if r > 0xFF {
			r = '?'
		}
		out = append(out, byte(r))
	}
	return out
}

// itxtChunk returns an iTXt chunk whose UTF-8 text is zlib compressed.
func itxtChunk(keyword, text string) ([]byte, error) {
	var data bytes.Buffer
	data.Write(latin1Bytes(keyword))
	data.WriteByte(0)
	data.WriteByte(1) // compression flag
	data.WriteByte(0) // compression method
	data.WriteByte(0) // empty language tag
	data.WriteByte(0) // empty translated keyword
	zw := zlib.NewWriter(&data)
	if _, err := zw.Write(utf8Bytes(text)); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return pngChunk("iTXt", data.Bytes()), nil
}

// utf8Bytes returns the UTF-8 encoding of text as Java's getBytes("UTF8")
// does: invalid sequences become '?'.
func utf8Bytes(s string) []byte {
	b := make([]byte, 0, len(s))
	for len(s) > 0 {
		r, size := utf8.DecodeRuneInString(s)
		if r == utf8.RuneError && size == 1 {
			b = append(b, '?')
		} else {
			b = append(b, s[:size]...)
		}
		s = s[size:]
	}
	return b
}

// physChunk returns the pHYs chunk upstream's addDpi writes: it gives the
// standard metadata a HorizontalPixelSize (millimeters per pixel) of
// dpi / 0.0254 / 1000, so the chunk holds 1000 / that value pixels per
// meter.
func physChunk(dpi int) []byte {
	value := float64(dpi) / 0.0254 / 1000
	// The value goes through Double.toString and Float.parseFloat.
	size, _ := strconv.ParseFloat(strconv.FormatFloat(value, 'g', -1, 64), 32)
	ppm := uint32(int32(math.Floor(float64(float32(1000)/float32(size)) + 0.5)))
	data := make([]byte, 9)
	binary.BigEndian.PutUint32(data, ppm)
	binary.BigEndian.PutUint32(data[4:], ppm)
	data[8] = 1 // unit: meter
	return pngChunk("pHYs", data)
}

// insertChunks copies a PNG stream, inserting chunks before the first
// IDAT chunk.
func insertChunks(w io.Writer, encoded []byte, extra [][]byte) error {
	if len(encoded) < len(signature) {
		return ErrNotPNG
	}
	bw := bufio.NewWriter(w)
	bw.Write(encoded[:len(signature)])
	p := len(signature)
	inserted := false
	for p+8 <= len(encoded) {
		length := int(binary.BigEndian.Uint32(encoded[p:]))
		kind := string(encoded[p+4 : p+8])
		end := p + 12 + length
		if end > len(encoded) {
			return ErrNotPNG
		}
		if kind == "IDAT" && !inserted {
			for _, c := range extra {
				bw.Write(c)
			}
			inserted = true
		}
		bw.Write(encoded[p:end])
		p = end
	}
	return bw.Flush()
}
